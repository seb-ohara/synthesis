'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { _electron } = require('playwright');
const ROOT = path.resolve(__dirname, '../..');

test('reasoning slider applies model levels after a drag, supports keys, and restores failures', async t => {
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'synthesis-reasoning-'));
  const env = { ...process.env, SYNTHESIS_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: [ROOT], cwd: ROOT, env });
  t.after(async () => { await app.close(); fs.rmSync(userData, { recursive: true, force: true }); });
  const page = await app.firstWindow();
  const pane = page.locator('.ws-view.active .chat-body:not(.tab-hidden)').first();
  await pane.waitFor();
  const id = await pane.evaluate(el => el.id.slice('panel-'.length));
  await app.evaluate(({ ipcMain, BrowserWindow }, id) => {
    ipcMain.removeAllListeners('chat:command'); globalThis.__reasoningCommands = [];
    ipcMain.on('chat:command', (_event, payload) => globalThis.__reasoningCommands.push(payload.message));
    const send = event => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event });
    send({ type: 'response', command: 'get_messages', success: true, data: { messages: [] } });
    send({ type: 'response', command: 'get_state', success: true, data: { model: { provider: 'openai', id: 'test' }, thinkingLevel: 'low' } });
    send({ type: 'response', command: 'get_available_thinking_levels', success: true, data: { levels: ['off', 'low', 'high'] } });
  }, id);
  const trigger = pane.locator('.chat-reasoning-trigger');
  await trigger.click();
  const slider = pane.locator('.chat-reasoning-slider');
  await slider.waitFor();
  assert.equal(await slider.getAttribute('aria-valuetext'), 'Low');
  assert.equal(await pane.locator('.chat-reasoning-tick').count(), 3);
  const alignment = await slider.evaluate(element => { const track = element.querySelector('.chat-reasoning-track').getBoundingClientRect(); const fill = element.querySelector('.chat-reasoning-fill').getBoundingClientRect(); return Math.abs(track.top - fill.top); });
  assert.ok(alignment < 1, `reasoning fill is ${alignment}px below its track`);
  const box = await slider.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width - 1, box.y + box.height / 2);
  assert.equal((await app.evaluate(() => globalThis.__reasoningCommands)).filter(c => c.type === 'set_thinking_level').length, 0);
  await page.mouse.up();
  await page.waitForFunction(() => globalThis.document.querySelector('.chat-reasoning-slider')?.getAttribute('aria-valuetext') === 'High');
  let commands = await app.evaluate(() => globalThis.__reasoningCommands);
  assert.equal(commands.filter(c => c.type === 'set_thinking_level').at(-1).level, 'high');
  await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event: { type: 'response', command: 'set_thinking_level', success: true } }), id);
  await page.waitForFunction(() => document.querySelector('.chat-reasoning-slider')?.getAttribute('aria-disabled') === 'false');
  await slider.focus(); await page.keyboard.press('ArrowLeft');
  commands = await app.evaluate(() => globalThis.__reasoningCommands);
  assert.equal(commands.filter(c => c.type === 'set_thinking_level').at(-1).level, 'low');
  await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event: { type: 'response', command: 'set_thinking_level', success: false, error: 'Rejected' } }), id);
  await page.waitForFunction(() => document.querySelector('.chat-reasoning-slider')?.getAttribute('aria-valuetext') === 'High');
  assert.equal(await pane.locator('.chat-reasoning-label').innerText(), 'High');
  await page.keyboard.press('Escape'); assert.equal(await trigger.getAttribute('aria-expanded'), 'false');
});

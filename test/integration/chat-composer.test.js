const ROOT = path.resolve(__dirname, '../..');

test('composer grows and its Git menu follows the active pane', async t => {
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'synthesis-composer-'));
  const env = { ...process.env, SYNTHESIS_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: [ROOT], cwd: ROOT, env });
  t.after(async () => { await app.close(); fs.rmSync(userData, { recursive: true, force: true }); });
  const page = await app.firstWindow();
  await page.waitForSelector('.ws-view.active .chat-body');
  const input = page.locator('.ws-view.active .chat-composer textarea').first();
  await page.waitForFunction(() => { const b = document.querySelector('.ws-view.active .chat-body').getBoundingClientRect(); const c = document.querySelector('.ws-view.active .chat-composer').getBoundingClientRect(); return Math.abs(b.top + b.height / 2 - c.top - c.height / 2) < 2; });
  const centered = await page.evaluate(() => { const body = document.querySelector('.ws-view.active .chat-body').getBoundingClientRect(); const composer = document.querySelector('.ws-view.active .chat-composer').getBoundingClientRect(); return Math.abs((body.top + body.height / 2) - (composer.top + composer.height / 2)); });
  assert.ok(centered < 2, `empty composer should be centered: ${centered}px`);
  assert.match(await page.locator('.ws-view.active .pane-tab-select').innerText(), /No project \/ New chat/);
  assert.equal(await page.locator('.ws-view.active .pane-tab-close').count(), 0);
  const tabId = await page.locator('.ws-view.active .chat-body').evaluate(el => el.id.slice('panel-'.length));
  await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event: { type: 'response', command: 'get_messages', success: true, data: { messages: [{ role: 'user', content: 'A message' }] } } }), tabId);
  await page.waitForFunction(() => !document.querySelector('.ws-view.active .chat-body').classList.contains('chat-empty'));
  await page.waitForFunction(() => { const body = document.querySelector('.ws-view.active .chat-body').getBoundingClientRect(); const composer = document.querySelector('.ws-view.active .chat-composer').getBoundingClientRect(); return Math.abs(body.bottom - composer.bottom - 24) < 2; });
  const initial = await input.evaluate(el => el.getBoundingClientRect().height);
  assert.ok(initial >= 20 && initial < 30, `single-line height was ${initial}`);
  await input.fill('One line\nTwo lines\nThree lines');
  const grown = await input.evaluate(el => el.getBoundingClientRect().height);
  assert.ok(grown > initial + 30, `multiline height ${grown} did not grow`);
  await input.fill('');
  assert.ok(Math.abs(await input.evaluate(el => el.getBoundingClientRect().height) - initial) < 1);
  assert.equal(await page.locator('#files-toggle-btn').count(), 0);
  await page.locator('.ws-view.active .pane-btn[data-action="splitRight"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.ws-view.active .tile').length === 2);
  const git = page.locator('.ws-view.active .tile').last().locator('.chat-git');
  await git.click();
  assert.equal(await git.getAttribute('aria-expanded'), 'true');
  const dimensions = await page.evaluate(() => {
    const a = document.querySelector('.ws-view.active .tile.active .chat-git').getBoundingClientRect();
    const p = document.querySelector('#git-panel').getBoundingClientRect();
    return { anchorX: a.left, anchorY: a.top, panelX: p.left, panelBottom: p.bottom, width: innerWidth, panelRight: p.right };
  });
  assert.ok(Math.abs(dimensions.panelX - dimensions.anchorX) < 2 || dimensions.panelRight <= dimensions.width - 7);
  assert.ok(dimensions.panelBottom <= dimensions.anchorY);
  await page.keyboard.press('Escape');
  assert.equal(await git.getAttribute('aria-expanded'), 'false');
  assert.equal(await git.evaluate(el => document.activeElement === el), true);
});

test('Pi commands, formatting and working/settled groups remain usable', async t => {
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'synthesis-composer-tools-'));
  const env = { ...process.env, SYNTHESIS_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: [ROOT], cwd: ROOT, env });
  t.after(async () => { await app.close(); fs.rmSync(userData, { recursive: true, force: true }); });
  const page = await app.firstWindow(); await page.waitForSelector('.ws-view.active .chat-body');
  await page.waitForFunction(() => !document.querySelector('.ws-view.active .chat-model-trigger').disabled, null, { timeout: 30000 });
  const chevronOffset = await page.locator('[data-section="working"] .conversation-section-toggle').evaluate(element => { const button = element.getBoundingClientRect(); const chevron = element.querySelector('svg').getBoundingClientRect(); return Math.abs(button.top + button.height / 2 - chevron.top - chevron.height / 2); });
  assert.ok(chevronOffset < 1, `section chevron is off-center by ${chevronOffset}px`);
  const pane = page.locator('.ws-view.active .chat-body:not(.tab-hidden)');
  const id = await pane.evaluate(el => el.id.slice('panel-'.length));
  await app.evaluate(({ ipcMain }) => { ipcMain.removeAllListeners('chat:command'); globalThis.__commands = []; ipcMain.on('chat:command', (_event, payload) => globalThis.__commands.push(payload.message)); });
  const input = pane.locator('textarea'); await input.fill('/comp');
  await page.waitForSelector('.chat-command-option'); assert.match(await pane.locator('.chat-command-menu').innerText(), /compact/);
  await input.fill('a\nb'); await input.focus(); await input.evaluate(el => el.setSelectionRange(0, el.value.length));
  await pane.locator('.chat-format-toggle').click(); await pane.locator('[data-format="bullet"]').click();
  assert.equal(await input.inputValue(), '- a\n- b');
  await input.fill('/compact'); await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('.chat-status-text')?.textContent === 'Compacting');
  assert.ok((await app.evaluate(() => globalThis.__commands)).some(command => command.type === 'compact'));
  await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event: { type: 'response', command: 'compact', success: true, data: {} } }), id);
  await page.waitForFunction(() => document.querySelector('.chat-status-text')?.textContent === 'Thinking');
  await input.fill('/tree'); await input.press('Enter');
  await pane.getByText('Pi’s /tree command is not available in Synthesis yet.').waitFor();
  assert.equal((await app.evaluate(() => globalThis.__commands)).some(command => command.type === 'prompt' && command.message === '/tree'), false);
  await input.fill('/name A useful title'); await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('.ws-view.active .pane-tab-select').textContent.includes('A useful title'));
  assert.ok((await app.evaluate(() => globalThis.__commands)).some(command => command.type === 'set_session_name' && command.name === 'A useful title'));
  await page.locator('[data-section="working"] .conversation-section-toggle').click();
  await input.fill('A task'); await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('[data-section="working"] .chat-card'));
  assert.equal(await page.locator('[data-section="working"] .conversation-section-toggle').getAttribute('aria-expanded'), 'true');
  assert.ok(await page.locator('.conversation-transition').count());
  await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event: { type: 'agent_settled', aborted: false } }), id);
  await page.waitForFunction(() => !document.querySelector('[data-section="working"] .chat-card'));
  assert.equal(await page.locator('.chat-card .ws-status.done').innerText(), 'Done');
  assert.equal(await page.locator('.chat-card .ws-status.done .ws-status-indicator').innerText(), '');
  assert.equal(await page.locator('.chat-card .ws-status.done').evaluate(element => getComputedStyle(element).color), 'rgb(131, 168, 118)');
  await page.locator('.chat-card').filter({ hasText: 'A useful title' }).click();
  assert.equal(await page.locator('.chat-card .ws-status.done').count(), 0);
  const card = page.locator('.chat-card').filter({ hasText: 'A useful title' }); await card.hover(); await card.locator('.conversation-settle').click();
  assert.equal(await page.locator('[data-section="settled"] .chat-card').count(), 1);
  assert.ok(await page.locator('.conversation-transition').count());
  assert.equal(await page.locator('[data-section="settled"] .conversation-section-toggle').getAttribute('aria-expanded'), 'false');
  await page.locator('[data-section="settled"] .conversation-section-toggle').click();
  assert.equal(await page.locator('[data-section="settled"] .chat-card').isVisible(), true);
});

test('snoozed chats return at the selected time and section headers show counts', async t => {
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'synthesis-snooze-'));
  const env = { ...process.env, SYNTHESIS_USER_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: [ROOT], cwd: ROOT, env });
  t.after(async () => { await app.close(); fs.rmSync(userData, { recursive: true, force: true }); });
  const page = await app.firstWindow(); await page.waitForSelector('.ws-view.active .chat-body');
  const id = await page.locator('.ws-view.active .chat-body').evaluate(el => el.id.slice('panel-'.length));
  await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.getAllWindows()[0].webContents.send('chat:event', { id, event: { type: 'response', command: 'get_messages', success: true, data: { messages: [{ role: 'user', content: 'A snoozed conversation' }] } } }), id);
  const card = page.locator('.chat-card').filter({ hasText: 'A snoozed conversation' }); await card.waitFor(); await card.hover(); await card.locator('.conversation-snooze').click();
  await page.locator('#snooze-dialog [data-snooze="hour"]').click();
  assert.equal(await page.locator('[data-section="snoozed"] .chat-card').count(), 1);
  assert.ok(await page.locator('.conversation-transition').count());
  const header = page.locator('[data-section="snoozed"] .conversation-section-toggle');
  assert.match(await header.innerText(), /Snoozed\s+1/); assert.equal(await header.getAttribute('aria-expanded'), 'false');
  await header.click();
  await page.evaluate(() => { const row = conversationRows().find(item => item.title.includes('A snoozed conversation')); setChatMeta(row.key, { snoozedUntil: Date.now() + 150 }); });
  await page.waitForFunction(() => !document.querySelector('[data-section="snoozed"] .chat-card'));
  assert.equal(await page.locator('.chat-card').filter({ hasText: 'A snoozed conversation' }).count(), 1);
  await card.hover(); await card.locator('.conversation-snooze').click();
  const custom = await page.evaluate(() => { const d = new Date(Date.now() + 2 * 86400000); const pad = n => String(n).padStart(2, '0'); return `${d.getFullYear()}-${pad(d.getMonth()+1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`; });
  await page.locator('#snooze-custom').fill(custom); await page.locator('#snooze-custom-form button').click();
  assert.equal(await page.locator('[data-section="snoozed"] .chat-card').count(), 1);
  await page.locator('[data-section="snoozed"] .chat-card').hover(); await page.locator('[data-section="snoozed"] .conversation-snooze').click();
  assert.equal(await page.locator('[data-section="snoozed"] .chat-card').count(), 0);
});
